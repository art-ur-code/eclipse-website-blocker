function resolveLanguage(setting, uiLanguage = "") {
  if (Object.hasOwn(I18N_STRINGS, setting)) return setting;

  const [base, region] = uiLanguage.toLowerCase().split(/[-_]/);
  const exact = region ? `${base}_${region.toUpperCase()}` : base;
  for (const code of [exact, I18N_BASE_FALLBACK[base], base]) {
    if (Object.hasOwn(I18N_STRINGS, code)) return code;
  }
  return "en";
}

function t(lang, key, vars = {}) {
  const text = I18N_STRINGS[lang]?.[key] ?? I18N_STRINGS.en[key];
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

async function getLanguage() {
  const result = await chrome.storage.sync.get({ [I18N_LANGUAGE_KEY]: "auto" });
  return resolveLanguage(result[I18N_LANGUAGE_KEY], chrome.i18n.getUILanguage());
}

if (typeof module !== "undefined") {
  module.exports = { I18N_LANGUAGES, I18N_STRINGS, resolveLanguage, t };
}
